import assert from "node:assert/strict";
import { mkdir, readFile } from "node:fs/promises";
import { chromium } from "playwright";

const ico = await readFile("src-tauri/icons/icon.ico");
assert.equal(ico.readUInt16LE(2), 1, "ICO image type");
const sizes = Array.from({ length: ico.readUInt16LE(4) }, (_, index) => {
	const start = 6 + index * 16;
	const width = ico[start] || 256;
	assert.equal(width, ico[start + 1] || 256);
	return width;
});
for (const size of [16, 24, 32, 48, 64, 256])
	assert.ok(sizes.includes(size), `Missing ICO size ${size}`);
const browser = await chromium.launch({ channel: "msedge", headless: true });
try {
	let html = `<html><body style="margin:0;background:#eef1f6;font:14px 'Segoe UI',sans-serif;color:#273449;padding:30px"><h2>SSR2Clash icon verification</h2><p>Actual size and 4× enlargement, generated by Tauri CLI</p>`;
	for (const [folder, background] of [
		["small", "#ffffff"],
		["tray-light", "#f6f7fa"],
		["tray-dark", "#18212f"],
	]) {
		html += `<section style="background:${background};padding:18px;margin-top:16px;border-radius:10px;color:${folder === "tray-dark" ? "#fff" : "#273449"}"><strong>${folder}</strong><div style="display:flex;align-items:center;gap:24px;margin-top:14px">`;
		for (const size of [16, 24, 32]) {
			const png = await readFile(
				`src-tauri/icons/${folder}/${size}x${size}.png`,
			);
			assert.equal(png.readUInt32BE(16), size);
			assert.equal(png.readUInt32BE(20), size);
			assert.equal(png[25], 6, "PNG must be RGBA");
			const url = `data:image/png;base64,${png.toString("base64")}`;
			html += `<div style="display:flex;align-items:center;gap:10px"><img alt="${size}px" width="${size}" height="${size}" src="${url}"><img alt="4x ${size}px" width="${size * 4}" height="${size * 4}" style="image-rendering:pixelated" src="${url}"><span>${size}px</span></div>`;
		}
		html += "</div></section>";
	}
	html += "</body></html>";
	const page = await browser.newPage({ viewport: { width: 950, height: 760 } });
	await page.setContent(html);
	await mkdir("output/playwright", { recursive: true });
	await page.screenshot({
		path: "output/playwright/icon-preview.png",
		fullPage: true,
	});
} finally {
	await browser.close();
}
console.log(
	`PASS ICO sizes ${sizes.join(", ")}; nine RGBA PNGs; headless contact sheet saved`,
);
